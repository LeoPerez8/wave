const SHORTCUTS = "android.app.shortcuts";

const isLauncherFilter = (filter: IntentFilter): boolean =>
  (filter.action ?? []).some((a) => a.$["android:name"] === "android.intent.action.MAIN") &&
  (filter.category ?? []).some((c) => c.$["android:name"] === "android.intent.category.LAUNCHER");

/**
 * Points Android at the shortcuts file from every launcher entry. Android reads it only
 * from launcher activities, and Wave's are the launcher icons' aliases (`launcherIcons.ts`),
 * one of them on at a time; so this runs after those are declared. Replaces any pointer
 * from an earlier run.
 */
export const addShareShortcuts = (manifest: Manifest): Manifest => {
  const application = manifest.manifest.application?.[0];
  if (application === undefined) throw new Error("AndroidManifest.xml has no <application>");
  const forwarder = "expo.modules.wavenative.recognize.RecognizeShortcutActivity";
  application.activity = [
    ...(application.activity ?? []).filter((activity) => activity.$["android:name"] !== forwarder),
    {
      $: {
        "android:name": forwarder,
        "android:exported": "true",
        "android:taskAffinity": "",
        "android:theme": "@android:style/Theme.NoDisplay",
        "android:excludeFromRecents": "true",
        "android:noHistory": "true",
      },
    },
  ];
  const entries: ManifestEntry[] = [
    ...(application.activity ?? []),
    ...(application["activity-alias"] ?? []),
  ];
  for (const entry of entries) {
    if (!(entry["intent-filter"] ?? []).some(isLauncherFilter)) continue;
    const pointer: MetaData = {
      $: { "android:name": SHORTCUTS, "android:resource": "@xml/shortcuts" },
    };
    entry["meta-data"] = [
      ...(entry["meta-data"] ?? []).filter((m) => m.$["android:name"] !== SHORTCUTS),
      pointer,
    ];
  }
  const tile = "expo.modules.wavenative.recognize.RecognizeTileService";
  // Expo omits service labels and icons from its manifest attribute type.
  const tileAttributes = {
    "android:name": tile,
    "android:exported": "true" as const,
    "android:permission": "android.permission.BIND_QUICK_SETTINGS_TILE",
    "android:label": "@string/recognize_song",
    "android:icon": "@drawable/ic_recognize",
  };
  application.service = [
    ...(application.service ?? []).filter((service) => service.$["android:name"] !== tile),
    {
      $: tileAttributes,
      "intent-filter": [
        { action: [{ $: { "android:name": "android.service.quicksettings.action.QS_TILE" } }] },
      ],
    },
  ];
  return manifest;
};
