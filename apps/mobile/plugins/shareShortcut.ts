/**
 * Wave's sharing shortcut on Android (#205): a share target for shared text in the
 * shortcuts resource, so the dynamic "Import to Wave" shortcut that `ShareShortcut.kt`
 * publishes shows in the share sheet's direct-share row. `withShareShortcut.ts` applies
 * these at prebuild.
 */
import type { AndroidConfig } from "expo/config-plugins";

type Manifest = AndroidConfig.Manifest.AndroidManifest;
type IntentFilter = AndroidConfig.Manifest.ManifestIntentFilter;
type MetaData = AndroidConfig.Manifest.ManifestMetaData;
/** An activity or alias. Expo's types leave out an activity's meta-data, which it can have. */
export type ManifestEntry = (
  | AndroidConfig.Manifest.ManifestActivity
  | AndroidConfig.Manifest.ManifestActivityAlias
) & { "meta-data"?: MetaData[] };

/**
 * The share target's category. `ShareShortcut.kt` gives the published shortcut the same
 * one: Android shows a dynamic shortcut as a share target only when their categories match.
 */
export const SHARE_TARGET_CATEGORY = "dev.leoperez.wave.category.IMPORT_SHARED_LINK";

/**
 * The resources, by path under `android/app/src/main/res`: the shortcuts file with a
 * share target that sends shared text to MainActivity, as picking Wave from the share
 * sheet's app list does. It declares no static shortcut.
 */
export const shareShortcutFiles = (packageName: string): Readonly<Record<string, string>> => ({
  "xml/shortcuts.xml": `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/shareShortcut.ts. -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
  <share-target android:targetClass="${packageName}.MainActivity">
    <data android:mimeType="text/plain" />
    <category android:name="${SHARE_TARGET_CATEGORY}" />
  </share-target>
</shortcuts>
`,
});

const SHORTCUTS = "android.app.shortcuts";

const isLauncherFilter = (filter: IntentFilter): boolean =>
  (filter.action ?? []).some((a) => a.$["android:name"] === "android.intent.action.MAIN") &&
  (filter.category ?? []).some((c) => c.$["android:name"] === "android.intent.category.LAUNCHER");

/**
 * Points Android at the shortcuts file from every launcher entry. Android reads it only
 * from launcher activities, and Wave's are the launcher icons' aliases (`launcherIcons.ts`),
 * one of them on at a time; so this runs after those are declared. Replaces any pointer
 * from an earlier run.
 */
export const addShareShortcuts = (manifest: Manifest): Manifest => {
  const application = manifest.manifest.application?.[0];
  if (application === undefined) throw new Error("AndroidManifest.xml has no <application>");
  const entries: ManifestEntry[] = [
    ...(application.activity ?? []),
    ...(application["activity-alias"] ?? []),
  ];
  for (const entry of entries) {
    if (!(entry["intent-filter"] ?? []).some(isLauncherFilter)) continue;
    const pointer: MetaData = {
      $: { "android:name": SHORTCUTS, "android:resource": "@xml/shortcuts" },
    };
    entry["meta-data"] = [
      ...(entry["meta-data"] ?? []).filter((m) => m.$["android:name"] !== SHORTCUTS),
      pointer,
    ];
  }
  return manifest;
};
