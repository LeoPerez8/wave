/**
 * Android's entry points: the Import to Wave share target (#205), the static
 * Recognize Song shortcut and its Quick Settings tile (#772). `withShareShortcut.ts`
 * applies them at prebuild.
 */
import type { AndroidConfig } from "expo/config-plugins";

type Manifest = AndroidConfig.Manifest.AndroidManifest;
type IntentFilter = AndroidConfig.Manifest.ManifestIntentFilter;
type MetaData = AndroidConfig.Manifest.ManifestMetaData;
/** An activity or alias. Expo's types leave out an activity's meta-data, which it can have. */
export type ManifestEntry = (
  AndroidConfig.Manifest.ManifestActivity | AndroidConfig.Manifest.ManifestActivityAlias
) & { "meta-data"?: MetaData[] };

/**
 * The share target's category. `ShareShortcut.kt` gives the published shortcut the same
 * one: Android shows a dynamic shortcut as a share target only when their categories match.
 */
