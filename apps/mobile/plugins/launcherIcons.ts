/**
 * Wave's launcher icons on Android: one activity alias of MainActivity per
 * pair of palette inks (Core's `LAUNCHER_ICONS`, 25 × 25), each with an
 * adaptive icon of vector waves on black. `withLauncherIcons.ts` applies these at prebuild.
 */
import {
  LAUNCHER_ICON_ART,
  LAUNCHER_ICONS,
  MANIFEST_LAUNCHER_ICON,
  type LauncherIcon,
} from "@wave/core";
import type { AndroidConfig } from "expo/config-plugins";

import { launcherAlias } from "../src/settings/launcherAlias.ts";

type Manifest = AndroidConfig.Manifest.AndroidManifest;
type IntentFilter = AndroidConfig.Manifest.ManifestIntentFilter;

const MAIN = "android.intent.action.MAIN";
const LAUNCHER = "android.intent.category.LAUNCHER";
const MAIN_ACTIVITY = ".MainActivity";

const isLauncherFilter = (filter: IntentFilter): boolean =>
  (filter.action ?? []).some((a) => a.$["android:name"] === MAIN) &&
  (filter.category ?? []).some((c) => c.$["android:name"] === LAUNCHER);

const launcherFilter = (): IntentFilter => ({
  action: [{ $: { "android:name": MAIN } }],
  category: [{ $: { "android:name": LAUNCHER } }],
});

const iconResource = (icon: LauncherIcon): string => `ic_launcher_${icon.id}`;

/**
 * Moves Wave's app-drawer entry from MainActivity to one alias per icon. Only
 * Core's `MANIFEST_LAUNCHER_ICON` is on, so Wave shows once; Settings switches
 * them at runtime (`LauncherIconSwitcher`). It stays teal over ember, not the
 * white default: an install that never switched icons has that alias on only
 * through the manifest, and enabling another here would swap its icon on
 * update, which drops it from the home screen. Aliases come after
 * MainActivity, as Android requires, and replace any from an earlier run.
 */
export const addLauncherAliases = (manifest: Manifest): Manifest => {
  const application = manifest.manifest.application?.[0];
  if (application === undefined) throw new Error("AndroidManifest.xml has no <application>");
  const main = application.activity?.find((a) => a.$["android:name"] === MAIN_ACTIVITY);
  if (main === undefined) throw new Error(`AndroidManifest.xml has no ${MAIN_ACTIVITY}`);
  main["intent-filter"] = (main["intent-filter"] ?? []).filter((f) => !isLauncherFilter(f));

  const ours = new Set(LAUNCHER_ICONS.map((icon) => `.${launcherAlias(icon)}`));
  application["activity-alias"] = [
    ...(application["activity-alias"] ?? []).filter((a) => !ours.has(a.$?.["android:name"] ?? "")),
    ...LAUNCHER_ICONS.map((icon) => ({
      $: {
        "android:name": `.${launcherAlias(icon)}`,
        "android:targetActivity": MAIN_ACTIVITY,
        "android:enabled": icon === MANIFEST_LAUNCHER_ICON ? ("true" as const) : ("false" as const),
        "android:exported": "true" as const,
        "android:icon": `@mipmap/${iconResource(icon)}`,
        "android:roundIcon": `@mipmap/${iconResource(icon)}`,
      },
      "intent-filter": [launcherFilter()],
    })),
  ];
  return manifest;
};

const XML_HEADER = '<?xml version="1.0" encoding="utf-8"?>';

const wavePath = (pathData: string, colour: string): string =>
  `  <path
    android:pathData="${pathData}"
    android:strokeColor="${colour}"
    android:strokeWidth="${LAUNCHER_ICON_ART.strokeWidth}"
    android:strokeLineCap="round"
    android:strokeLineJoin="round" />`;

/** Waves as a vector drawable the size of an adaptive icon layer. */
const vectorDrawable = (...paths: string[]): string => {
  const size = LAUNCHER_ICON_ART.viewport;
  return `${XML_HEADER}
<!-- Generated by plugins/launcherIcons.ts from Core's LAUNCHER_ICON_ART. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
  android:width="${size}dp"
  android:height="${size}dp"
  android:viewportWidth="${size}"
  android:viewportHeight="${size}">
${paths.join("\n")}
</vector>
`;
};

const MONOCHROME = "ic_launcher_wave_monochrome";

/** One wave in one ink; every pair with that ink in that place layers it. */
const waveResource = (wave: "top" | "bottom", ink: string): string =>
  `ic_launcher_wave_${wave}_${ink}`;

/**
 * The icons' resources, by path under `android/app/src/main/res`: per ink a
 * top-wave and a bottom-wave drawable, and per icon a foreground layering its
 * primary's top wave and its secondary's bottom wave, and an adaptive icon
 * (black ground, that foreground, and the shared monochrome waves the system
 * tints for themed icons). The drawables grow with the inks, not the pairs.
 */
export const launcherIconFiles = (): Readonly<Record<string, string>> => {
  const files: Record<string, string> = {
    [`drawable/${MONOCHROME}.xml`]: vectorDrawable(
      wavePath(LAUNCHER_ICON_ART.top, "#ffffff"),
      wavePath(LAUNCHER_ICON_ART.bottom, "#ffffff"),
    ),
  };
  for (const icon of LAUNCHER_ICONS) {
    const top = waveResource("top", icon.primary);
    const bottom = waveResource("bottom", icon.secondary);
    files[`drawable/${top}.xml`] ??= vectorDrawable(wavePath(LAUNCHER_ICON_ART.top, icon.top));
    files[`drawable/${bottom}.xml`] ??= vectorDrawable(
      wavePath(LAUNCHER_ICON_ART.bottom, icon.bottom),
    );
    const name = iconResource(icon);
    files[`drawable/${name}_foreground.xml`] = `${XML_HEADER}
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
  <item android:drawable="@drawable/${top}" />
  <item android:drawable="@drawable/${bottom}" />
</layer-list>
`;
    files[`mipmap-anydpi-v26/${name}.xml`] = `${XML_HEADER}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@android:color/black" />
  <foreground android:drawable="@drawable/${name}_foreground" />
  <monochrome android:drawable="@drawable/${MONOCHROME}" />
</adaptive-icon>
`;
  }
  return files;
};
