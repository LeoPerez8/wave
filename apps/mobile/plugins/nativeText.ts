import { nativeEn } from "../../../packages/core/src/catalogue/nativeEn.ts";
import { nativePtBr } from "../../../packages/core/src/catalogue/nativePtBr.ts";

/** Native defaults are generated from the same catalogue as JS. */
export const nativeCatalogueKotlin =
  (): string => `// Generated by plugins/nativeText.ts. Do not edit.
package expo.modules.wavenative.locale

object NativeCatalogue {
${Object.entries({ en: nativeEn, pt: nativePtBr })
  .map(
    ([language, entries]) =>
      `  val ${language} = mapOf(\n${Object.entries(entries)
        .map(([key, value]) => `    ${JSON.stringify(key)} to ${JSON.stringify(value)},`)
        .join("\n")}\n  )`,
  )
  .join("\n")}
}
`;

const xml = (value: string) =>
  value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll("'", "\\'");
export const nativeTextResources = (): Readonly<Record<string, string>> =>
  Object.fromEntries(
    Object.entries({ values: nativeEn, "values-pt": nativePtBr }).map(([folder, text]) => [
      `${folder}/wave_text.xml`,
      `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n${Object.entries(text)
        .map(([key, value]) => `  <string name="wave_${key.toLowerCase()}">${xml(value)}</string>`)
        .join(
          "\n",
        )}\n${folder === "values-pt" ? `  <string name="recognize_song">${xml(text.recognize)}</string>\n` : ""}</resources>\n`,
    ]),
  );
