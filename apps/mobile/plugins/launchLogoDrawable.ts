// The splash's moving logo: an AnimatedVectorDrawable Android plays from the
// first frame of the launch splash, before Wave's code runs, so it runs on
// the RenderThread like the playing underline (`wave_underline.xml`). Written
// at prebuild from Core's `launchLogoWaves`: each wave's path runs a
// wavelength past the logo and slides left by one per sweep, while trimming
// keeps its round caps where the still logo's are. Every sweep starts and
// ends on the still logo, so a stopped animation (Android 12's time limit,
// "Remove animations") shows the logo as it is. The colours are the splash
// style's theme attributes (`launchSplashResources.ts`). Pure, so the app
// tests can check it without prebuild.
import { LAUNCH_LOGO, launchLogoWaves, type LaunchLogoTrim, type LogoWave } from "@wave/core";

import { LAUNCH_LOGO_ATTRS } from "./launchSplashResources.ts";

const number = (n: number): string => String(Math.round(n * 1000) / 1000);

/** A sweep's length, over and over, as animator attributes laid out at `indent`. */
const repeat = (indent: string): string =>
  [
    `android:duration="${LAUNCH_LOGO.cycleMs}"`,
    `android:repeatCount="infinite"`,
    `android:repeatMode="restart"`,
  ].join(`\n${indent}`);

const trimAnimator = (property: string, trim: LaunchLogoTrim): string => `
          <objectAnimator
              android:propertyName="${property}"
              android:valueFrom="${trim.from}"
              android:valueTo="${trim.to}"
              android:valueType="floatType"
              ${repeat("              ")}>
            <aapt:attr name="android:interpolator">
              <pathInterpolator android:pathData="${trim.curve}" />
            </aapt:attr>
          </objectAnimator>`;

/** The drawable's XML (`res/drawable/launch_logo.xml`). */
export const launchLogoDrawable = (): string => {
  const waves = launchLogoWaves();
  const { size } = LAUNCH_LOGO;
  const colour = { top: LAUNCH_LOGO_ATTRS.primary, bottom: LAUNCH_LOGO_ATTRS.secondary };
  const order: LogoWave[] = ["top", "bottom"];
  const groups = order
    .map(
      (wave) => `
      <group android:name="${wave}_slide">
        <path
            android:name="${wave}"
            android:pathData="${waves[wave].path}"
            android:strokeColor="?attr/${colour[wave]}"
            android:strokeWidth="${number(waves[wave].stroke)}"
            android:strokeLineCap="round"
            android:trimPathStart="${waves[wave].trimStart.from}"
            android:trimPathEnd="${waves[wave].trimEnd.from}" />
      </group>`,
    )
    .join("");
  const targets = order
    .map(
      (wave) => `
  <target android:name="${wave}_slide">
    <aapt:attr name="android:animation">
      <objectAnimator
          android:propertyName="translateX"
          android:valueFrom="0"
          android:valueTo="${number(-waves[wave].slide)}"
          android:valueType="floatType"
          android:interpolator="@android:anim/linear_interpolator"
          ${repeat("          ")} />
    </aapt:attr>
  </target>
  <target android:name="${wave}">
    <aapt:attr name="android:animation">
      <set>${trimAnimator("trimPathStart", waves[wave].trimStart)}${trimAnimator("trimPathEnd", waves[wave].trimEnd)}
      </set>
    </aapt:attr>
  </target>`,
    )
    .join("");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/launchLogoDrawable.ts from @wave/core's launchLogoWaves. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
  <aapt:attr name="android:drawable">
    <vector
        android:width="${size}dp"
        android:height="${size}dp"
        android:viewportWidth="${size}"
        android:viewportHeight="${size}">${groups}
    </vector>
  </aapt:attr>${targets}
</animated-vector>
`;
};

/** The theme attributes the logo's colours come from (`res/values/launch_logo_attrs.xml`). */
export const launchLogoAttrs = (): string => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/launchLogoDrawable.ts: each splash style sets the logo's colours. -->
<resources>
  <attr name="${LAUNCH_LOGO_ATTRS.primary}" format="color" />
  <attr name="${LAUNCH_LOGO_ATTRS.secondary}" format="color" />
</resources>
`;
